// scripts/build-cro-tower-page.mjs
//
// Builds the standalone /cro-tower page from its sources and writes it as a TS string module,
// so the route handler (src/app/cro-tower/route.ts) serves it with no file reads at runtime.
//
//   sources  src/lib/cro-tower-page/{body.html, app.js, extra.css}
//            + the CSS block of the approved demo, copied 1:1
//            (ppcos/goolets/created/cro-control-tower-demo/index.html, vendored as demo.css)
//   output   src/lib/cro-tower-page/html.ts
//
//   node scripts/build-cro-tower-page.mjs      (re-run after editing any source, then commit both)
import fs from 'node:fs'
import path from 'node:path'

const dir = path.join(process.cwd(), 'src/lib/cro-tower-page')
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8')

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow">
<title>Goolets · Web Funnel · CRO</title>
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Playfair+Display:wght@400;500;600;700&display=swap">
<style>
${read('demo.css')}
${read('extra.css')}
</style>
</head>
<body>
${read('body.html')}
<script>
${read('app.js')}
</script>
</body>
</html>
`
const out = `// GENERATED by scripts/build-cro-tower-page.mjs — do not edit; edit src/lib/cro-tower-page/* and re-run.
export const CRO_TOWER_HTML = ${JSON.stringify(html)}
`
fs.writeFileSync(path.join(dir, 'html.ts'), out)
console.log(`wrote src/lib/cro-tower-page/html.ts (${html.length} chars)`)
